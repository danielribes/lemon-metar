import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const AIRPORTS_URL = 'https://raw.githubusercontent.com/davidmegginson/ourairports-data/main/airports.csv';
const STATIONS_URL = 'https://tgftp.nws.noaa.gov/data/observations/metar/stations/';
const OUTPUT = new URL('../src/airports/data.js', import.meta.url);

const STATION_LINK = /href="([A-Z][A-Z0-9]{3})\.TXT"/g;
const CLOSED = 'closed';
const MIN_EXPECTED_AIRPORTS = 5000;

/** Fields that can hold a station code, from least to most reliable. */
const CODE_FIELDS = ['gps_code', 'icao_code', 'ident'];

/** Parses CSV text into one object per row, keyed by the header. */
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;

  const endField = () => {
    row.push(field);
    field = '';
  };
  const endRow = () => {
    endField();
    rows.push(row);
    row = [];
  };

  for (let index = 0; index < text.length; index++) {
    const character = text[index];

    if (quoted && character === '"' && text[index + 1] === '"') {
      field += '"';
      index++;
    } else if (character === '"') {
      quoted = !quoted;
    } else if (quoted) {
      field += character;
    } else if (character === ',') {
      endField();
    } else if (character === '\n') {
      endRow();
    } else if (character !== '\r') {
      field += character;
    }
  }
  if (field !== '' || row.length > 0) endRow();

  const [header, ...records] = rows;
  return records.map((record) => Object.fromEntries(header.map((name, index) => [name, record[index]])));
}

export const parseStations = (listing) => [...new Set([...listing.matchAll(STATION_LINK)].map((match) => match[1]))];

/** Returns a code to name map for the stations found in the airport rows, sorted by code. */
export function selectAirports(rows, stations) {
  const open = rows.filter((row) => row.type !== CLOSED && row.name);

  const nameByCode = new Map();
  for (const field of CODE_FIELDS) {
    for (const row of open) {
      if (row[field]) nameByCode.set(row[field], row.name);
    }
  }

  return Object.fromEntries(
    stations
      .filter((code) => nameByCode.has(code))
      .sort()
      .map((code) => [code, nameByCode.get(code)]),
  );
}

export function renderModule(airports) {
  const entries = Object.entries(airports).map(([code, name]) => `  ${JSON.stringify(code)}: ${JSON.stringify(name)},`);
  return [
    '// Generated by scripts/update-airports.js. Do not edit.',
    '// Airport names from OurAirports (https://ourairports.com/data/).',
    'export const airports = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

async function download(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Download failed with status ${response.status}: ${url}`);
  return response.text();
}

async function main() {
  const [csv, listing] = await Promise.all([download(AIRPORTS_URL), download(STATIONS_URL)]);
  const stations = parseStations(listing);
  const airports = selectAirports(parseCsv(csv), stations);

  const count = Object.keys(airports).length;
  if (count < MIN_EXPECTED_AIRPORTS) {
    throw new Error(`Only ${count} airports found. Keeping the current data.`);
  }

  await writeFile(OUTPUT, renderModule(airports));
  console.log(`${count} airports written, out of ${stations.length} stations.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
